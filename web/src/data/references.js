/** Flatten a reference into compact events [[midi|-1, dur], ...]. */
export function referenceEvents(ref) {
  return ref.bars.flat();
}

/** Sounding line {pitch, onset} on the 16th grid for a list of compact events. */
export function compactToLine(compact) {
  const pitch = [];
  const onset = [];
  for (const [p, d] of compact) {
    for (let k = 0; k < d; k++) {
      pitch.push(p < 0 ? null : p);
      onset.push(p >= 0 && k === 0);
    }
  }
  return { pitch, onset };
}
